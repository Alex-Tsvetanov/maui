EMBED_REL = "../../../../maui-reference/pages"

GENERATED_MARK = "GENERATED by port/tools/e2e/e2e.py"


def pascal(key: str) -> str:
    return "".join(w[:1].upper() + w[1:] for w in key.split("_") if w)


def shared_keys() -> list[str]:
    if not os.path.isdir(PAGES):
        return []
    return sorted(os.path.splitext(f)[0] for f in os.listdir(PAGES) if f.endswith(".xaml"))


def legacy_keys() -> list[str]:
    """Local gallery_xaml/Views twins not yet migrated to the shared pages dir."""
    if not os.path.isdir(VIEWS):
        return []
    return sorted(
        os.path.splitext(f)[0]
        for f in os.listdir(VIEWS)
        if f.endswith(".xaml") and not f.endswith((".xaml.hpp", ".xaml.cpp"))
    )


def all_keys() -> list[str]:
    return sorted(set(shared_keys()) | set(legacy_keys()))


def load_manifest() -> list[dict]:
    if not os.path.isfile(MANIFEST):
        return []
    with open(MANIFEST, encoding="utf-8") as fh:
        return json.load(fh)


# ---------------------------------------------------------------- gen: C++ TU templates -------------
HPP = '''#pragma once
// {name}.xaml.hpp — page-construction declaration for the `{name}` page (the C++ analog of a .xaml.cs
// partial's generated factory). Bodyless on purpose: the #embed and the build_page call live in the
// sibling translation unit {name}.xaml.cpp, so main.cpp depends only on this declaration.
//
// {mark} gen — do not edit by hand; re-run the generator instead.

#include <memory>

#include "maui/controls/content_page.hpp"
#include "maui/xaml/xaml_loader.hpp" // xaml_load_options (the application/theme threading knob)

namespace examples::Views
{{
    // options threads the loader knobs — most importantly the application pointer, so
    // {{AppThemeBinding}} resolves against the app's CURRENT requested theme and re-applies on
    // RequestedThemeChanged (defaulted: theme-static hydration, the old behavior).
    [[nodiscard]] std::unique_ptr<maui::controls::content_page> {name}_page(
        const maui::xaml::xaml_load_options& options = {{}});
}} // namespace examples::Views
'''

# Shared-page TU: #embed points OUT of the repo's cpp tree at the canonical maui-reference/pages file,
# and static_asserts compile-time-lock the naming triple (file <-> key <-> x:Class).
CPP_SHARED = '''// {name}.xaml.cpp — implements examples::Views::{name}_page() (declared in {name}.xaml.hpp).
//
// This TU OWNS the compile-time XAML: the COMPILER embeds the CANONICAL SHARED page
// port/maui-reference/pages/{name}.xaml — the exact same bytes real .NET MAUI compiles via XamlC +
// code-behind (MauiReference.Pages.{pascal}Page) — and build_page hydrates it through the runtime
// loader into a fresh page_impl<no_view_model>. One file, two frameworks, zero divergence.
//
// {mark} gen — do not edit by hand; re-run the generator instead.

#include "Views/{name}.xaml.hpp"

#include <cstddef>
#include <string_view>

#include "maui/fixed_string.hpp"
#include "maui/xaml_build.hpp"

namespace
{{
    // The raw markup, embedded by the compiler (resolved relative to this source file, like a quoted
    // #include). The two-line embed is the canonical form (a #embed directive cannot live inside a
    // macro body — see fixed_string.hpp).
    constexpr unsigned char {name}_xaml_bytes[] = {{
#embed "{embed_rel}/{name}.xaml"
    }};
    constexpr maui::fixed_string {name}_xaml{{{name}_xaml_bytes}};

    // Compile-time naming-triple lock: the embedded bytes must be a ContentPage whose x:Class matches
    // this page's key-derived MAUI partial class (the lint's runtime check, enforced by the compiler).
    template <std::size_t N>
    constexpr bool bytes_contain(const unsigned char (&hay)[N], std::string_view needle)
    {{
        if (needle.empty() || N < needle.size())
        {{
            return needle.empty();
        }}
        for (std::size_t i = 0; i + needle.size() <= N; i++)
        {{
            bool match = true;
            for (std::size_t j = 0; j < needle.size(); j++)
            {{
                if (static_cast<char>(hay[i + j]) != needle[j])
                {{
                    match = false;
                    break;
                }}
            }}
            if (match)
            {{
                return true;
            }}
        }}
        return false;
    }}
    static_assert(bytes_contain({name}_xaml_bytes, "<ContentPage"));
    static_assert(bytes_contain({name}_xaml_bytes, "x:Class=\\"MauiReference.Pages.{pascal}Page\\""));
}} // namespace

namespace examples::Views
{{
    std::unique_ptr<maui::controls::content_page> {name}_page(const maui::xaml::xaml_load_options& options)
    {{
        // unique_ptr<page_impl<no_view_model>> upcasts to unique_ptr<content_page> on return.
        return maui::build_page<maui::no_view_model, {name}_xaml>(options);
    }}
}} // namespace examples::Views
'''

