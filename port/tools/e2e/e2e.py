def _osa(script: str) -> str:
    return subprocess.run(["osascript", "-e", script], capture_output=True, text=True).stdout.strip()


def _find_window_id(pid: int, retries: int = 15, delay: float = 0.3) -> int | None:
    """The owning-PID's frontmost normal-layer on-screen window's CGWindowID, or None. Polls briefly
    since window creation isn't instant after process launch. Requires pyobjc-framework-Quartz
    (pip3 install pyobjc-framework-Quartz) — no extra macOS permission needed (unlike CGWindowListCreateImage,
    plain CGWindowListCopyWindowInfo doesn't require Screen Recording access to see other apps' window
    numbers/bounds/owner, only their *pixel content*, which screencapture -l reads via its own grant)."""
    import Quartz  # local import: optional dependency, only needed for maccatalyst capture

    for _ in range(retries):
        info = Quartz.CGWindowListCopyWindowInfo(Quartz.kCGWindowListOptionOnScreenOnly, Quartz.kCGNullWindowID)
        candidates = [w for w in (info or [])
                     if w.get("kCGWindowOwnerPID") == pid and w.get("kCGWindowLayer") == 0]
        if candidates:
            # Prefer the largest normal-layer window (skips any stray small utility window).
            def area(w):
                b = w.get("kCGWindowBounds", {})
                return b.get("Width", 0) * b.get("Height", 0)
            return int(max(candidates, key=area)["kCGWindowNumber"])
        time.sleep(delay)
    return None


def _launch_background(app: dict, env_pairs: dict[str, str]) -> int | None:
    """Launch the app BUNDLE via `open -g -n --env ...` (LaunchServices background launch — the app is
    never activated, so the operator's keyboard/mouse focus is untouched) and return the NEW process's
    pid, or None. `open` detaches, so the pid is found by diffing `pgrep -x <proc>` before/after."""
    bundle = os.path.abspath(os.path.join(os.path.dirname(app["bin"]), "..", ".."))
    before = set(subprocess.run(["pgrep", "-x", app["proc"]], capture_output=True,
                                text=True).stdout.split())
    cmd = ["open", "-g", "-n"]
    for k, v in env_pairs.items():
        cmd += ["--env", f"{k}={v}"]
    cmd.append(bundle)
    if subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode != 0:
        return None
    for _ in range(40):  # `open` returns before the process registers; poll for the new pid
        now = set(subprocess.run(["pgrep", "-x", app["proc"]], capture_output=True,
                                 text=True).stdout.split())
        fresh = now - before
        if fresh:
            return int(next(iter(fresh)))
        time.sleep(0.25)
    return None


def _maccat_shot(framework: str, key: str, theme: str, settle: float) -> bool:
    app = MACCAT_APPS[framework]
    if not os.path.isfile(app["bin"]):
        print(f"  ! missing binary for {framework}: {app['bin']}")
        return False
    # MAUI_CAPTURE_TINT_NORMAL: all three apps force tintAdjustmentMode=Normal so the never-activated
    # window's CONTENT renders exactly like the active state (see the header comment above).
    env_pairs = dict(app["env"](key, theme), MAUI_CAPTURE_TINT_NORMAL="1")
    pid = _launch_background(app, env_pairs)
    proc = None
    if pid is None:
        # LaunchServices launch failed (sandbox/quarantine/...) — direct binary exec. This DOES
        # self-activate (steals focus for the app's lifetime); loud in the log via the fallback line.
        env = dict(os.environ, **env_pairs)
        proc = subprocess.Popen([app["bin"]], env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        pid = proc.pid
    try:
        time.sleep(settle)
        subprocess.run(["killall", "-9", "ReportCrash"], stderr=subprocess.DEVNULL)
        subprocess.run(["killall", "UserNotificationCenter"], stderr=subprocess.DEVNULL)
        win_id = _find_window_id(pid)
        out = capture_out_path("maccatalyst", framework, key, theme)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        if win_id is not None:
            # -x: no capture-sound. -o: omit the drop-shadow padding (tight window-bounds crop).
            # -l: this specific window, by CGWindowID — reads that window's own backing store, so no
            # OTHER window (a system notification, another app, an IDE) can ever composite into the
            # shot, and the window needs neither focus nor front-of-stack placement.
            rc = subprocess.run(["screencapture", "-x", "-o", "-l", str(win_id), out]).returncode
            ok = rc == 0 and os.path.isfile(out)
            print(f"  {framework:5} {key:28} {'ok' if ok else 'FAIL'} (window {win_id})")
        else:
            # Fallback: no Quartz / no window found — the old fixed-rect + frontmost path (focus steal
            # + wrong-window-composite hazard; eyeball the resulting PNG).
            _osa(f'tell application "System Events" to set frontmost of '
                 f'(first process whose unix id is {pid}) to true')
            time.sleep(1.2)
            rect = app["rect"]
            got = _osa(f'tell application "System Events" to tell process "{app["proc"]}"\n'
                       "set p to position of window 1\nset s to size of window 1\n"
                       'return ((item 1 of p) as string) & "," & ((item 2 of p) as string) & "," & '
                       '((item 1 of s) as string) & "," & ((item 2 of s) as string)\nend tell')
            if got.count(",") == 3:
                rect = got
            rc = subprocess.run(["screencapture", "-x", f"-R{rect}", out]).returncode
            ok = rc == 0 and os.path.isfile(out)
            print(f"  {framework:5} {key:28} {'ok' if ok else 'FAIL'} (fallback rect {rect})")
        return ok
    finally:
        subprocess.run(["kill", "-9", str(pid)], stderr=subprocess.DEVNULL)
        if proc is not None:
            try:
                proc.wait(timeout=3)
            except Exception:
                pass
        time.sleep(0.4)


def _builder_twin_keys() -> set[str] | None:
    """Keys manifest.json marks builder_twin:false have NO code-first page in the `gallery` app — its
    MAUI_SAMPLE_PAGE dispatch (main.cpp make_selected_page) silently falls back to value_controls for an
    unrecognized name, so capturing "cpp" for one of these keys previously produced a MISLEADING
    wrong-page screenshot instead of skipping. Returns None (no filtering) if the manifest is empty/absent
    — all keys are treated as having a cpp twin, matching the old behavior for legacy/pre-manifest setups."""
    manifest = load_manifest()
    if not manifest:
        return None
    return {row["key"] for row in manifest if row.get("builder_twin", True)}


def cmd_capture(args: argparse.Namespace) -> int:
    if args.platform != "maccatalyst":
        print(f"error: platform {args.platform!r} not absorbed yet — use the legacy scripts under "
              "port/cpp/tools/parity/ (capture_all.py for ios, build_android_apphost*.sh + "
              "capture_all_csharp_android.sh for android, capture_appkit.py for appkit)")
        return 2
    frameworks = [f for f in args.framework.split(",") if f in MACCAT_APPS]
    themes = [t for t in args.theme.split(",") if t in ("light", "dark")]
    keys = args.keys or shared_keys()
    if not keys:
        print("no keys to capture (no shared pages yet and none given)")
        return 2
    twin_keys = _builder_twin_keys()
    print(f"capture maccatalyst: {len(keys)} key(s) x {frameworks} x {themes}")
    failures, skipped = 0, 0
    for theme in themes:
        for key in keys:
            for fw in frameworks:
                if fw == "cpp" and twin_keys is not None and key not in twin_keys:
                    print(f"  cpp   {key:28} skip (builder_twin:false — no code-first page)")
                    skipped += 1
                    continue
                if not _maccat_shot(fw, key, theme, args.settle):
                    failures += 1
    print(f"done ({failures} failure(s), {skipped} skipped)")
    return 1 if failures else 0


